// Helper to get questions for a quiz session
export const getQuestionsForQuiz = (
  categoryId: string,
  count: number = 10,
  difficulty?: string
): Question[] => {
  let pool = QUESTIONS.filter(q => q.category === categoryId);

  if (difficulty && difficulty !== 'all') {
    const filtered = pool.filter(q => q.difficulty === difficulty);
    if (filtered.length >= 3) {
      pool = filtered;
    }
  }

  // If pool has fewer questions than requested, supplement with other questions
  if (pool.length < count) {
    const others = QUESTIONS.filter(q => q.category !== categoryId);
    // Shuffle others
    const shuffledOthers = [...others].sort(() => 0.5 - Math.random());
    pool = [...pool, ...shuffledOthers.slice(0, count - pool.length)];
  }

  // Shuffle pool and take requested count
  return [...pool].sort(() => 0.5 - Math.random()).slice(0, count);
};

// Daily challenge questions: seed based on date string
export const getDailyQuestions = (): { questions: Question[]; dateKey: string } => {
  const dateKey = new Date().toISOString().slice(0, 10);
  // deterministic pseudo-random seed based on date digits
  let seed = 0;
  for (let i = 0; i < dateKey.length; i++) {
    seed = (seed << 5) - seed + dateKey.charCodeAt(i);
    seed |= 0;
  }
  const absSeed = Math.abs(seed);

  const shuffled = [...QUESTIONS].sort((a, b) => {
    const hashA = (a.id.charCodeAt(0) * absSeed) % 1000;
    const hashB = (b.id.charCodeAt(0) * absSeed) % 1000;
    return hashA - hashB;
  });

  return {
    questions: shuffled.slice(0, 10),
    dateKey,
  };
};
